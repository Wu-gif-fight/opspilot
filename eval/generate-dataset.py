cases = []
for source, questions in TOPICS:
    for question, intent, severity, terms, reference in questions:
        cases.append({
            "id": "case-" + str(len(cases) + 1),
            "question": question,
            "expectedSources": [source],
            "expectedTerms": terms,
            "referenceAnswer": reference,
            "expectedIntent": intent,
            "expectedSeverityLevel": severity,
            "groundedAnswerTerms": terms,
            "minGroundedAnswerTerms": min(2, len(terms)),
            "requiredAnswerTerms": terms[:1],
            "requiredHelpTerms": terms[:1],
            "forbiddenAnswerTerms": FORBIDDEN,
        })

out = "src/main/resources/rag-eval/opspilot-rag-eval.json"
with open(out, "w", encoding="utf-8") as f:
    json.dump(cases, f, ensure_ascii=False, indent=2)

from collections import Counter
print("total:", len(cases))
print("severity:", dict(Counter(c["expectedSeverityLevel"] for c in cases)))
print("intent:", dict(Counter(c["expectedIntent"] for c in cases)))
